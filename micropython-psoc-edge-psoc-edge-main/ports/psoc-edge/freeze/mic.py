# mic.py - ไมโครโฟนของบอร์ด แบบที่บรรทัดแรกไม่ต้องรู้อะไรเลย
#
# ทำไมต้องมี: การเปิดไมค์ด้วย machine.PDM_PCM ตรง ๆ ต้องรู้ชื่อขาสองขา
# อัตราสุ่ม อัตราดีซิเมชัน จำนวนบิต และช่องซ้ายขวา ทั้งห้าอย่างเป็นค่าของ
# บอร์ดใบนี้ที่ไม่มีวันเปลี่ยน ผู้เรียนคาบแรกไม่ควรต้องพิมพ์มันเพื่อจะรู้ว่า
# เสียงดังแค่ไหน และค่าดิบที่ได้กลับมายังมี DC offset ก้อนใหญ่ติดมาด้วย
# ซึ่งถ้าไม่หักออกก่อน ตัวเลขที่เห็นจะไม่เกี่ยวกับความดังเลย
#
#   ชั้นต้น        mic.start() แล้ว mic.level()          -> 0-100
#   ชั้นกลาง       mic.start(sens=5) · mic.rms() · mic.peak() · mic.stats()
#   ชั้นสูง        mic.read() เอารูปคลื่นไปทำต่อ หรือ machine.PDM_PCM ตรง ๆ
#
# rms peak level และ stats ลงไปคำนวณในภาษา C ที่ PDM_PCM.stats() ไม่ได้วนใน
# Python เพราะการวนทีละตัวอย่างกินเวลา 280 มิลลิวินาทีต่อครั้ง (วัดบนบอร์ด
# 2026-08-14) มิเตอร์จึงขยับได้แค่สามครั้งต่อวินาที และเสียงสั้น ๆ ตกลงไปใน
# ช่องว่างระหว่างสองครั้งจนไม่ปรากฏเลย ส่วน read() ยังอยู่ใน Python เพราะมันคืน
# list ของตัวอย่างจริง ๆ ซึ่งเลี่ยงการวนไม่ได้อยู่แล้ว
#
# ค่าที่ตั้งไว้ให้ตรงกับสายบนบอร์ด: P8_5 คือ PDM_CLK ช่อง 3 และ P8_6 คือ
# PDM_DATA ช่อง 3 (cycfg_routing.h) ดังนั้น format ต้องเป็น MONO_RIGHT
# ถ้าใช้ MONO_LEFT จะไปอ่านช่อง 2 ซึ่งบอร์ดใบนี้ไม่ได้ต่อไว้ แล้วจะเงียบสนิท

from machine import Pin, PDM_PCM
import time

SCK = "P8_5"
DATA = "P8_6"
RATE = 16000
DECIMATION = 96
BITS = 16

_pdm = None
_buf = None
_dc = 0             # ค่ากลางที่ไหลตามสัญญาณ ใช้หักออกก่อนวัดความดัง
_full = 32768       # สเกลเต็มของ 16 บิต ใช้แปลงเป็น 0-100


# ระดับความไวที่ผู้เรียนเลือกได้ แปลงเป็นค่าจริงของฮาร์ดแวร์ให้เอง
#
# สเกลของชิปกลับด้าน: เลข 0 คือขยาย 83 dB ซึ่งแรงที่สุด และเลขมากคือเบาลง
# จนถึง -67 dB ที่ 25 (cy_pdm_pcm_v2.h) ค่าเริ่มต้นเดิมของพอร์ตคือ 0 จึงขยาย
# สุดกำลังตลอดเวลาและสัญญาณอิ่มตัวทุกครั้ง ผู้เรียนไม่ควรต้องรู้เรื่องนี้
# ตัวเลขที่ให้เลือกจึงเป็น 1 ถึง 5 แบบตรงไปตรงมา ยิ่งมากยิ่งไวต่อเสียงเบา
_SENS = {1: 17, 2: 15, 3: 13, 4: 11, 5: 9}   # -> ค่า enum ของชิป


def start(sens=3, rate=RATE, samples=256):
    """เปิดไมค์ เรียกครั้งเดียวก่อนใช้งาน

    sens    1 ถึง 5 ยิ่งมากยิ่งไวต่อเสียงเบา ค่าเริ่มต้น 3 พอสำหรับเสียงพูด
    rate    อัตราสุ่ม ปกติ 16000 ไม่ต้องเปลี่ยนถ้าไม่มีเหตุผล
    samples จำนวนตัวอย่างต่อการอ่านหนึ่งครั้ง ยิ่งมากยิ่งนิ่งแต่ยิ่งช้า
    """
    global _pdm, _buf, _dc
    if _pdm is not None:
        stop()
    g = _SENS.get(sens, _SENS[3])
    _pdm = PDM_PCM(0, sck=Pin(SCK), data=Pin(DATA),
                   sample_rate=rate, decimation_rate=DECIMATION, bits=BITS,
                   format=PDM_PCM.MONO_RIGHT, left_gain=g, right_gain=g)
    _buf = bytearray(samples * 2)
    _dc = 0
    # ชุดแรกหลังเปิดยังไม่นิ่ง ทิ้งไปสองชุดแล้วค่อยเริ่มนับจริง
    for _ in range(2):
        try:
            _pdm.readinto(_buf)
        except OSError:
            pass
        time.sleep_ms(20)
    return True


def stop():
    """ปิดไมค์ คืนหน่วยความจำ"""
    global _pdm, _buf
    if _pdm is not None:
        try:
            _pdm.deinit()
        except Exception:
            pass
    _pdm = None
    _buf = None


def _grab():
    if _pdm is None:
        raise OSError("ยังไม่ได้เปิดไมค์ - เรียก mic.start() ก่อน")
    _pdm.readinto(_buf)
    return _buf


def raw():
    """อ่านหนึ่งชุดแล้วคืน buffer int16 ดิบ (ยังไม่หัก DC)

    คู่กับ dsp.fft_mag(mic.raw()) — สเปกตรัมจบใน C ทั้งเส้น ไม่ผ่านลูป
    แกะ byte ของ read() ที่กิน ~280 ms ต่อชุด (fft_mag หักค่าเฉลี่ยให้
    เองก่อน window — demean=True เป็นค่าปริยาย — DC ค้างของไมค์จึงไม่
    รั่วมาเป็นยอดปลอมที่ bin 1)
    """
    return _grab()


def read(n=None):
    """คืนค่าตัวอย่างเสียงเป็น list ของจำนวนเต็ม หัก DC ออกแล้ว

    ใช้ตอนอยากเห็นรูปคลื่นเอง หรือเอาไปทำ FFT ต่อ
    """
    global _dc
    raw = _grab()
    out = []
    total = 0
    count = len(raw) // 2
    for i in range(0, len(raw), 2):
        v = raw[i] | (raw[i + 1] << 8)
        if v > 32767:
            v -= 65536
        out.append(v)
        total += v
    # หักค่ากลางของบัฟเฟอร์นี้เอง ไม่ใช่ค่าที่ไหลตามข้ามบัฟเฟอร์
    #
    # เดิมใช้ค่าเฉลี่ยแบบไหลตาม ซึ่งตามไม่ทัน: วัดบนบอร์ด 2026-08-14 ค่าดิบ
    # มี DC ค้างเกือบเต็มสเกล และคลื่นจริงขี่อยู่บนนั้น ผลคือ level แสดงขนาด
    # ของ DC ไม่ใช่ความดังของเสียง หักค่าเฉลี่ยของชุดเดียวกันทิ้งไปตรง ๆ
    # ได้ทั้งกัน DC และกันการไหลช้า ๆ ของตัวกรอง CIC ไปพร้อมกัน
    _dc = total // count
    for i in range(len(out)):
        out[i] -= _dc

    # เคยลองใส่ตัวกรองความถี่ต่ำออกแบบขั้วเดียวตรงนี้ แล้ววัดได้แย่ลงชัดเจน
    # (วัดบนบอร์ด 2026-08-14: rms จาก 170 ในห้องเงียบ กลับขึ้นไป 24000 และ
    # peak ทะลุ 50000) เพราะสูตรที่ใช้เป็นผลต่างตัวติดกัน ซึ่งขยายความถี่สูง
    # อันเป็นที่อยู่ของสัญญาณรบกวน ไม่ใช่ตัดความถี่ต่ำอย่างที่ตั้งใจ
    # ถอดออกแล้ว หักค่าเฉลี่ยของบัฟเฟอร์อย่างเดียวให้ผลดีกว่า ถ้าจะใส่กลับ
    # ต้องเป็นตัวกรองที่ออกแบบมาจริง ไม่ใช่ผลต่างตัวติดกัน
    if n is not None and n < len(out):
        return out[:n]
    return out


def stats(fresh=True):
    """อ่านหนึ่งชุด แล้วคืน (rms, peak, dc) พร้อมกันในครั้งเดียว

    fresh   True คือทิ้งเสียงเก่าที่ค้างในคิว เอาเฉพาะช่วงล่าสุด ซึ่งเป็นสิ่ง
            ที่มิเตอร์ต้องการ ตั้ง False เมื่ออยากได้ทุกตัวอย่างเรียงตามลำดับ
    """
    global _dc
    if _pdm is None:
        raise OSError("ยังไม่ได้เปิดไมค์ - เรียก mic.start() ก่อน")
    r, p, _dc = _pdm.stats(_buf, fresh=fresh)
    return r, p, _dc


def lag():
    """เสียงที่ค้างรออยู่ในคิว คิดเป็นมิลลิวินาที - คือดีเลย์ที่จะเห็นบนจอ

    ถ้าลูปของเราอ่านช้ากว่าไมค์ผลิต ตัวเลขนี้จะไต่ขึ้นเรื่อย ๆ จนเต็มคิว
    แล้วทุกอย่างที่แสดงจะช้ากว่าความจริงเท่าค่านี้ตลอดไป
    """
    if _pdm is None:
        raise OSError("ยังไม่ได้เปิดไมค์ - เรียก mic.start() ก่อน")
    return _pdm.pending()


def peak():
    """ค่าสูงสุดในชุดล่าสุด 0 ถึง 32768 - ใช้จับเสียงตบมือ"""
    return stats()[1]


def rms():
    """ความดังเฉลี่ยแบบ RMS 0 ถึง 32768 - นิ่งกว่า peak ใช้ทำมิเตอร์"""
    return stats()[0]


# สเกลของหู ไม่ใช่สเกลของเลข
#
# เดิม level() คือ rms หารด้วยสเกลเต็ม 16 บิต ซึ่งอ่านง่ายแต่ใช้ไม่ได้จริง:
# วัดบนบอร์ด 14 ส.ค. 2026 ห้องเงียบได้ rms 30 เสียงพูดปกติราว 1000 ทั้งสองค่า
# หารด้วย 32768 แล้วปัดลงเป็นจำนวนเต็มได้ 0 เท่ากัน มิเตอร์จึงนิ่งสนิทที่ 0
# จนกว่าจะเอาปากจ่อไมค์ ซึ่งไม่ใช่สิ่งที่ผู้เรียนควรเจอในบรรทัดแรก
#
# หูคนได้ยินความดังเป็นอัตราส่วน ไม่ใช่ผลต่าง เสียง 1000 ดังกว่า 500 เท่ากับที่
# 500 ดังกว่า 250 สเกลนี้จึงนับเป็นอ็อกเทฟ (ทุกครั้งที่ค่าเพิ่มเป็นสองเท่า
# ได้คะแนนเท่ากัน) ตั้งแต่ rms 16 ซึ่งเงียบกว่าห้องเงียบ ไปจนสุดสเกล
# ผลที่ได้: เงียบ 7 · พูดปกติ 54 · ตะโกนหรือตบมือ 92-100
_FLOOR = 16          # ต่ำกว่านี้ถือว่า 0
_LO = 1024           # log2(16) x 256
_SPAN = 2816         # log2(32768) x 256 ลบด้วย _LO


def _log2_q8(v):
    """log2(v) คูณ 256 แบบจำนวนเต็ม ไม่ต้องพึ่ง math"""
    # นับบิตเอง เพราะพอร์ตนี้ไม่ได้เปิด int.bit_length() ไว้ (ลองบนบอร์ดแล้ว
    # ได้ AttributeError) วนไม่เกิน 16 รอบ ซึ่งเทียบกับ 32 ms ของการอ่านไมค์
    # แล้วแทบไม่มีต้นทุน
    bits = 0
    x = v
    while x:
        x >>= 1
        bits += 1
    # เลื่อนให้เหลือช่วง 256-511 เพื่ออ่านทศนิยมของอ็อกเทฟแบบเชิงเส้น
    # ซึ่งคลาดจากค่าจริงไม่เกิน 3% พอสำหรับมิเตอร์บนจอ 4.3 นิ้ว
    m = (v << (9 - bits)) if bits <= 9 else (v >> (bits - 9))
    return ((bits - 1) << 8) + (m - 256)


def level():
    """ความดังเป็นเปอร์เซ็นต์ 0 ถึง 100 - ตัวเลขที่เอาไปโชว์บนจอได้เลย"""
    r = rms()
    if r < _FLOOR:
        return 0
    v = (_log2_q8(r) - _LO) * 100 // _SPAN
    if v < 0:
        return 0
    return 100 if v > 100 else v
